-- candle's palette, defined in OKLCH: writes the colors Neovim (schema.lua) and kitty (config/kitty/candle.conf) read.
--
--   nvim -l nvim/lua/candle/build.lua           writes them
--   nvim -l nvim/lua/candle/build.lua --check   fails if they aren't what it would write
--
-- Every hue has the levels 100 (lightest) to 900, evenly spaced in OKLCH lightness, so a level is as light in one
-- hue as in another. A hue keeps its angle at every level, and its chroma follows the lightness (saturation ×
-- lightness), as far as sRGB reaches.

-- Lightness of 900, the background's (#1b1b1b), and of 200, the foreground's (#c0c0c0)
local DARK, LIGHT = 0.2221, 0.8078

-- Each hue's angle, and its chroma per unit of lightness
local HUES = {
  { 'gray', 0, 0 },
  { 'red', 23, 0.100 },
  { 'orange', 63, 0.100 },
  { 'yellow', 84, 0.088 },
  { 'green', 118, 0.085 },
  { 'aqua', 185, 0.047 },
  { 'blue', 246, 0.055 },
  { 'purple', 324, 0.080 },
  { 'pink', 346, 0.131 },
}

-- Levels in between: the editor's surfaces, which differ from the background by little, and the diff's backgrounds
local NUANCES = {
  gray = { 450, 825, 850, 860, 875, 905 },
  red = { 850 },
  green = { 850 },
  blue = { 850 },
}

-- Colors by role, which kitty shares
local ROLES = {
  { 'foreground', 'gray200' },
  { 'background', 'gray900' },
  { 'comment', 'gray600' },
  { 'selection', 'gray800' },
  { 'line', 'gray860' }, -- the cursor's line
  { 'window', 'gray850' }, -- statusline, tabline, separators
  { 'guide', 'gray905' }, -- 'colorcolumn'
}

-- kitty's options: it draws Neovim, which paints everything else
local KITTY = {
  { 'foreground', 'foreground' },
  { 'background', 'background' },
  { 'cursor', 'gray300' },
  { 'cursor_text_color', 'background' },
  { 'url_color', 'blue400' },
}

local function lightness(level)
  return DARK + (900 - level) / 700 * (LIGHT - DARK)
end

-- Linear sRGB of an OKLCH color (https://bottosson.github.io/posts/oklab/)
local function linear_srgb(l, c, h)
  local a, b = c * math.cos(math.rad(h)), c * math.sin(math.rad(h))
  local l_ = (l + 0.3963377774 * a + 0.2158037573 * b) ^ 3
  local m_ = (l - 0.1055613458 * a - 0.0638541728 * b) ^ 3
  local s_ = (l - 0.0894841775 * a - 1.2914855480 * b) ^ 3
  return {
    4.0767416621 * l_ - 3.3077115913 * m_ + 0.2309699292 * s_,
    -1.2684380046 * l_ + 2.6097574011 * m_ - 0.3413193965 * s_,
    -0.0041960863 * l_ - 0.7034186147 * m_ + 1.7076147010 * s_,
  }
end

local function in_gamut(rgb)
  for _, v in ipairs(rgb) do
    if v < -1e-7 or v > 1 + 1e-7 then
      return false
    end
  end
  return true
end

-- The color as hex, and the chroma it got: the most sRGB has, up to the one asked for
local function to_hex(l, c, h)
  if not in_gamut(linear_srgb(l, c, h)) then
    local lo, hi = 0, c
    for _ = 1, 40 do
      local mid = (lo + hi) / 2
      if in_gamut(linear_srgb(l, mid, h)) then
        lo = mid
      else
        hi = mid
      end
    end
    c = lo
  end
  local hex = '#'
  for _, v in ipairs(linear_srgb(l, c, h)) do
    v = math.min(1, math.max(0, v))
    v = v <= 0.0031308 and 12.92 * v or 1.055 * v ^ (1 / 2.4) - 0.055
    hex = hex .. ('%02x'):format(math.floor(v * 255 + 0.5))
  end
  return hex, c
end

local function palette()
  local colors, by_name = {}, {}
  for _, hue in ipairs(HUES) do
    local name, angle, saturation = unpack(hue)
    local levels = { 100, 200, 300, 400, 500, 600, 700, 800, 900 }
    vim.list_extend(levels, NUANCES[name] or {})
    table.sort(levels)
    for _, level in ipairs(levels) do
      local l = lightness(level)
      local hex, c = to_hex(l, saturation * l, angle)
      local color = { name = name .. level, hex = hex, l = l, c = c, h = angle }
      table.insert(colors, color)
      by_name[color.name] = color
    end
  end
  return colors, by_name
end

local function schema_lua(colors)
  local lines = { '-- Generated by build.lua (nvim -l nvim/lua/candle/build.lua): edit that, not this.', 'local schema = {' }
  local hue
  for _, color in ipairs(colors) do
    local name = color.name:match('^%a+')
    if name ~= hue then
      table.insert(lines, (hue and '\n' or '') .. '  -- ' .. name)
      hue = name
    end
    table.insert(lines, ("  %-9s = '%s', -- oklch(%.1f%% %.3f %d)"):format(color.name, color.hex, color.l * 100, color.c, color.h))
  end
  table.insert(lines, '}\n')
  for _, role in ipairs(ROLES) do
    table.insert(lines, ('schema.%s = schema.%s'):format(role[1], role[2]))
  end
  table.insert(lines, '\nreturn schema')
  return table.concat(lines, '\n') .. '\n'
end

local function kitty_conf(by_name)
  local roles = {}
  for _, role in ipairs(ROLES) do
    roles[role[1]] = role[2]
  end
  local lines = { '# Generated by nvim/lua/candle/build.lua: edit that, not this.' }
  for _, option in ipairs(KITTY) do
    local color = by_name[roles[option[2]] or option[2]]
    table.insert(lines, ('%-17s %s'):format(option[1], color.hex))
  end
  return table.concat(lines, '\n') .. '\n'
end

local function read(path)
  local file = io.open(path, 'r')
  if not file then
    return nil
  end
  local content = file:read('*a')
  file:close()
  return content
end

local here = vim.fs.dirname(vim.fs.abspath(debug.getinfo(1, 'S').source:sub(2)))
local repo = vim.fs.normalize(here .. '/../../..')
local colors, by_name = palette()
local outputs = {
  { here .. '/schema.lua', schema_lua(colors) },
  { repo .. '/config/kitty/candle.conf', kitty_conf(by_name) },
}

local check = arg[1] == '--check'
local stale = false
for _, output in ipairs(outputs) do
  local path, content = unpack(output)
  if read(path) ~= content then
    if check then
      io.stderr:write(path .. " isn't what build.lua writes\n")
      stale = true
    else
      local file = assert(io.open(path, 'w'))
      file:write(content)
      file:close()
      io.stdout:write('wrote ' .. path .. '\n')
    end
  end
end
os.exit(stale and 1 or 0)
