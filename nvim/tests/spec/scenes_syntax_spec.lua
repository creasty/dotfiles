describe('Scenes: syntax', function()
  for _, sample in ipairs(SAMPLES) do
    local filetype, file, lines = unpack(sample)
    it(filetype, function()
      local nvim = scenes.nvim(filetype)
      nvim:edit(file, lines)
      t.eq(filetype, nvim:filetype())
      scenes.check(nvim, filetype, ('%s: %s'):format(filetype, file))
    end)
  end
end)
